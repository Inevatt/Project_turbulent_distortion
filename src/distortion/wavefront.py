"""Фаза Колмогорова на зрачке и PSF из неё. Общий код D2 и D3.

Вся физика D2 — одна формула (Mao, Chimitt, Chan, ICCV 2021, ур. 2):

    h = |F{ W(rho) * exp(i*phi(rho)) }|^2

W — зрачок, phi — фаза в радианах. При phi = 0 выходит пятно Айри,
при случайной phi — спеклы. Остаётся задать статистику phi.

Способ задания — не фурье-экран, а базис Цернике (Noll 1976):

    phi(rho) = sum_j a_j Z_j(rho),   a ~ N(0, R_Z),   R_Z из Нолля

Так делает вся линия Chan group (TurbSim -> P2S -> ATSyn -> DATUM).
У фурье-экрана расходимость спектра на низких частотах обрезается
сеткой, экран молча теряет наклон и дефокус и требует субгармоник.
Здесь низкие моды и есть базис — обрезать нечего.

R_Z пропорциональна (D/r0)^(5/3), поэтому корень матрицы считается
один раз при D/r0 = 1, а per-call остаётся множитель (D/r0)^(5/6).
Так же устроен референс: random_ = sqrt(Dr0**(5/3)) * randn.

Наклон вынут наружу. a_2 и a_3 — это ровно наклон фронта, он только
двигает PSF, не меняя формы. Он разыгрывается вместе с остальными
модами (в R_Z есть недиагональные члены, связывающие наклон с a_7,
a_8), но применяется как сдвиг всего кадра — той же машинерией, что
в D1. Три следствия: ядро остаётся компактным; экскурсии наклона
не надо покрывать окном ядра; D1 и D2 отличаются РОВНО формой ядра.
Референс делает так же: zernike[..., :2] идёт в сдвиг пикселей,
zernike[..., 2:] — в размытие.

Перевод наклона в пиксели. Z_2 = 2*rho*cos(theta) = 4x/D, значит
градиент фазы 4*a_2/D рад/м, угол прихода (lambda/2pi)*(4 a_2/D)
= (2/pi)*a_2*(lambda/D). То есть сдвиг в пикселях есть a_2, взятое
в единицах lambda/D, умноженное на 2/pi. Проверено численно по
центроиду PSF: check_d2.py, расхождение 0.1%.

Числа, не унаследованные от референса, а измеренные (check_d2.py):

  K_MODES. У авторов 36. Это мало: при 36 модах средняя OTF полной
  фазы идёт выше H_LE Фрида на 13% при D/r0 = 5 и на 15% при D/r0 = 3,
  то есть D2 оказывается слабее, чем заявленный D/r0, а D/r0 — общая
  ось всех четырёх уровней

  N_GRID. Связь жёсткая: lambda/D в пикселях = N_GRID / диаметр
  зрачка в ячейках, то есть паддинг зрачка задаёт масштаб. При
  N_GRID = 128 зрачок выходит 65.8 ячейки, дифракционное пятно
  FWHM = 2.004 px против заданных 2.0. Сетка 256 даёт те же OTF
  до третьего знака и вчетверо дороже.

  PSF_RADIUS_PX. Бюджет margin_px = 40 при обрезке наклона на 4
  сигмы оставляет ядру ровно 19. В окно +-19 попадает 97.8% энергии
  при D/r0 = 5, и 98.2% из них теряется на крыльях Айри, а не на
  турбулентности: гауссиана D0 крыльев не имеет вовсе. Ядро
  перенормируется на единицу после обрезки, как это делает
  gaussian_filter в D0.

Передискретизации нет намеренно. |.|^2 удваивает полосу поля, но
мы берём ТОЧЕЧНЫЕ отсчёты интенсивности, а точечная выборка
и поэлементный квадрат коммутируют: |u[n]|^2 суть отсчёты
непрерывной интенсивности. D0 тоже сэмплирует гауссиану в центрах
пикселей (gaussian_filter не интегрирует по площади). Восьмикратная
передискретизация у авторов нужна потому, что у них шаг матрицы
задан извне физикой камеры и PSF приходится интерполировать
на сетку пикселей. Здесь масштаб назначается через
diffraction_fwhm_px, интерполяции нет.
"""

import math

import numpy as np

from ..optics import TILT_CLIP, lambda_over_d_px

K_MODES = 231         # моды Нолля 1..K: все радиальные порядки до 13
N_GRID = 128          # сетка FFT, в которую вписан зрачок
PSF_RADIUS_PX = 19    # полуширина вырезаемого ядра
RAD_TO_LOD = 2.0 / np.pi   # a_2 [рад] -> сдвиг в единицах lambda/D


def noll_nm(j):
    """Индекс Нолля -> (n, m). Чётное j — косинус, нечётное — синус."""
    n, rest = 0, j - 1
    while rest > n:
        n += 1
        rest -= n
    m = (-1) ** j * ((n % 2) + 2 * int((rest + ((n + 1) % 2)) / 2.0))
    return n, m


def zernike(j, rho, theta):
    """Полином Цернике в нормировке Нолля: среднее Z_j^2 по диску равно 1."""
    n, m = noll_nm(j)
    am = abs(m)
    rad = np.zeros_like(rho)
    for s in range((n - am) // 2 + 1):
        rad += (-1) ** s * math.factorial(n - s) / (
            math.factorial(s)
            * math.factorial((n + am) // 2 - s)
            * math.factorial((n - am) // 2 - s)
        ) * rho ** (n - 2 * s)
    if m == 0:
        return np.sqrt(n + 1.0) * rad
    harm = np.cos(am * theta) if m > 0 else np.sin(am * theta)
    return np.sqrt(2.0 * (n + 1.0)) * rad * harm


def noll_cov(k_modes):
    """Ковариация коэффициентов Цернике при D/r0 = 1, индексы Нолля 1..K.

    Noll 1976; форма записи взята из референсной реализации авторов
    (turbStats._nollCovMat). Ненулевые элементы только у мод с равным
    |m| и одинаковой чётностью индекса — это и есть межмодовая
    корреляция, вынесенная в заголовок Chimitt & Chan 2020.
    Пистон (j = 1) не трогаем: на PSF он не влияет, дальше отбрасывается.
    """
    c = np.zeros((k_modes, k_modes))
    for i in range(1, k_modes + 1):
        ni, mi = noll_nm(i)
        for j in range(1, k_modes + 1):
            nj, mj = noll_nm(j)
            if abs(mi) != abs(mj) or (i - j) % 2:
                continue
            num = math.gamma(14.0 / 3.0) * math.gamma((ni + nj - 5.0 / 3.0) / 2.0)
            den = (math.gamma((-ni + nj + 17.0 / 3.0) / 2.0)
                   * math.gamma((ni - nj + 17.0 / 3.0) / 2.0)
                   * math.gamma((ni + nj + 23.0 / 3.0) / 2.0))
            c[i - 1, j - 1] = (0.0072 * np.pi ** (8.0 / 3.0)
                               * np.sqrt((ni + 1.0) * (nj + 1.0))
                               * (-1.0) ** ((ni + nj - 2 * abs(mi)) / 2.0)
                               * num / den)
    return c


def centroid_px(kernel):
    """Первый момент ядра относительно центра массива, (dy, dx).

    В data.py уходит именно он, а не наклонные моды: содержимое кадра
    уезжает на первый момент применённого ядра, а у спекл-PSF он
    отличается от наклона на 0.38 px RMS при D/r0 = 5. Это не ошибка
    генератора: снятие наклона по Цернике (best linear fit) не то же
    самое, что сдвиг центроида изображения, — Фрид оговаривает это
    сноской, а Kaiser 2000 разбирает подробно.

    Отдать наружу наклон значило бы оставить эти 0.38 px в таргете
    и опустить потолок PSNR уровня примерно на 4 дБ против D1 —
    при том, что различаться уровни обязаны только формой ядра.
    Ядро D1 центрировано на своём сдвиге точно, поэтому там разницы
    между двумя способами нет (check_d1: 0.0002 px).
    """
    ax = np.arange(len(kernel)) - len(kernel) // 2
    return float(kernel.sum(1) @ ax), float(kernel.sum(0) @ ax)


class Kolmogorov:
    """Генератор фазы и PSF. Строится один раз на уровень, дальше только вызовы."""

    def __init__(self, diffraction_fwhm_px, k_modes=K_MODES, n_grid=N_GRID):
        self.n_grid = int(n_grid)
        self.px_per_rad = RAD_TO_LOD * lambda_over_d_px(diffraction_fwhm_px)

        # Диаметр зрачка в ячейках сетки задаётся масштабом изображения:
        # lambda/D в пикселях есть отношение сетки FFT к зрачку. Целым
        # его делать незачем, маска — просто круг радиуса d/2.
        d_cells = self.n_grid / lambda_over_d_px(diffraction_fwhm_px)
        ax = np.arange(self.n_grid) - self.n_grid / 2.0
        x, y = np.meshgrid(ax, ax)
        rho = np.hypot(x, y) / (d_cells / 2.0)
        self.mask = rho <= 1.0
        theta = np.arctan2(y, x)[self.mask]
        rho = rho[self.mask]

        # Пистон выброшен, поэтому индекс 0 массива — это j = 2, наклон по x.
        self.basis = np.stack(
            [zernike(j, rho, theta) for j in range(2, k_modes + 1)])
        cov = noll_cov(k_modes)[1:, 1:]
        w, v = np.linalg.eigh(cov)
        self.root = v * np.sqrt(np.maximum(w, 0.0))
        self.sigma_tilt_rad = np.sqrt(cov[0, 0])   # при D/r0 = 1

    def coeffs(self, d_over_r0, rng):
        """Одна реализация коэффициентов. Тратит ровно K-1 случайных чисел."""
        a = (self.root @ rng.normal(size=len(self.root))) * d_over_r0 ** (5.0 / 6.0)
        # Обрезка наклона нужна не ради статистики (дефицит дисперсии
        # 0.01%), а ради margin: выброс за 4 сигмы утащил бы окно ядра
        # за пределы кропа с запасом. Та же обрезка и тем же TILT_CLIP,
        # что в D1.
        lim = TILT_CLIP * self.sigma_tilt_rad * d_over_r0 ** (5.0 / 6.0)
        a[:2] = np.clip(a[:2], -lim, lim)
        return a

    def tilt_sigma_px(self, d_over_r0):
        """Сигма дрожания кадра по одной оси, px."""
        return self.px_per_rad * self.sigma_tilt_rad * d_over_r0 ** (5.0 / 6.0)

    def shift_px(self, a):
        """Сдвиг кадра (dy, dx) из наклонных мод. a_2 — по x, a_3 — по y."""
        return self.px_per_rad * a[1], self.px_per_rad * a[0]

    def psf(self, a, radius, sigma_px = 0.0):
        """Ядро (2r+1, 2r+1), сумма 1, центр реализации сдвинут на shift_px(a).

        Наклон оставлен внутри фазы: FFT сдвигает пятно на сетке ТОЧНО,
        без интерполяции, поэтому дробная часть сдвига попадает в ядро
        даром. Отдельный ndimage.shift добавил бы своё размытие,
        зависящее от величины сдвига — ровно то, от чего отказались в D1.
        """
        u = np.zeros((self.n_grid, self.n_grid), dtype=np.complex128)
        u[self.mask] = np.exp(1j * (a @ self.basis))
        h = np.abs(np.fft.fft2(u)) ** 2
        if sigma_px:
            f2 = np.fft.fftfreq(self.n_grid) ** 2
            g = np.exp(-2.0 * (np.pi * sigma_px) ** 2 * (f2[:, None] + f2))
            h = np.fft.ifft2(np.fft.fft2(h) * g).real
        h = np.fft.fftshift(h)
        c = self.n_grid // 2
        h = h[c - radius:c + radius + 1, c - radius:c + radius + 1]
        return h / h.sum()
