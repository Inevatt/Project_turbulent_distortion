"""D3 плюс шум сенсора: единственный уровень с не-турбулентным искажением.

ЗАЧЕМ. Лестница D0-D3 моделирует распространение света через атмосферу и
обрывается на выходе объектива. Реальный кадр после этого проходит сенсор,
и шум оттуда не появится, сколько ни уточняй оптику. Строка отвечает на
вопрос, который лестница задать не может: нужно ли вообще моделировать
шум, или дальнейшее уточнение физики важнее.

Прецедент: Rim et al. (RSBlur, ECCV 2022) разбирали такую же лестницу для
размытия движения и нашли, что добавление гауссова шума в синтетику дало
+1.57 дБ на реальных данных — один из крупнейших одиночных факторов их
конвейера, причём на съёмке камерой высокого класса при минимальном ISO.
Сигма и схема розыгрыша взяты оттуда же.

КАК ЧИТАЕТСЯ. Сравниваются строки D3 (a) и D3+шум (b) на двух столбцах:

    b - a > 0 на реальном, <= 0 на D1  ->  шум специфичен
    b - a > 0 на обоих                 ->  общая робастность, про шум ничего

Контроль — столбец D1, а не D3: на D3 строка D3 диагональна и обойти её
нельзя по построению, отрицательный результат там не различал бы ничего.
На D1 обе сравниваемые строки внедиагональны. Разности между столбцами НЕ
вычитаются: знаменатели разные.

ПОЧЕМУ ШУМ ПОСЛЕДНИМ. Ключ rng в data.py не содержит имени уровня, поэтому
d3 и d3n при одном (seed, epoch, idx) получают ОДНУ И ТУ ЖЕ реализацию
фазы и поля смещений — шум разыгрывается после и предыдущие числа не
трогает. Строки отличаются ровно шумом, сравнение парное по построению.

ЧТО УПРОЩЕНО. Реальный шум сенсора сигнально-зависим: пуассонов дробовой
плюс гауссов шум считывания, оба искажаются ISP камеры. Здесь аддитивный
гауссов в sRGB — та же базовая точка, с которой RSBlur сравнивает свой
полный конвейер. В ограничениях работы названо явно.
"""

import numpy as np

from .d3 import D3Anisoplanatic

NOISE_SIGMA = 0.0112   # Rim et al., оценка по снимку цветовой мишени, шкала [0, 1]
SIGMA_SPREAD = 0.5     # сигма из U((1-s)*NOISE_SIGMA, (1+s)*NOISE_SIGMA), как у них


class D3Noise(D3Anisoplanatic):
    """Сигма — модульная константа, а не аргумент: train.py строит ВСЕ уровни
    реестра одним позиционным diffraction_fwhm_px для проверки margin_px.
    Обязательный второй аргумент уронил бы запуск любого уровня."""

    name = "d3n"

    # support_radius_px наследуется от D3: шум поточечный, носителя не
    # расширяет, margin_px остаётся общим для всех уровней.

    def __call__(self, img, d_over_r0, rng):
        out, shift = super().__call__(img, d_over_r0, rng)

        # float() обязателен: numpy-скаляр float64 поднял бы float32-массив
        # до float64 и удвоил бы память батча.
        sigma = float(rng.uniform((1.0 - SIGMA_SPREAD) * NOISE_SIGMA,
                                  (1.0 + SIGMA_SPREAD) * NOISE_SIGMA))
        out = out + rng.standard_normal(out.shape, dtype=np.float32) * sigma

        # Обрезка не косметика: сенсор физически не отдаёт значений за
        # пределами диапазона, и контракт в base.py требует [0, 1]. Эталон
        # не трогается, он и так чистый.
        return np.clip(out, 0.0, 1.0, out=out), shift
